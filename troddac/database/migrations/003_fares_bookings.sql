CREATE TABLE fare_matrices (
    id               INT UNSIGNED NOT NULL AUTO_INCREMENT,
    name             VARCHAR(80)  NOT NULL,
    base_fare        DECIMAL(8,2) NOT NULL,
    base_distance_km DECIMAL(5,2) NOT NULL DEFAULT 1.00,
    per_km_rate      DECIMAL(8,2) NOT NULL,
    minimum_fare     DECIMAL(8,2) NOT NULL,
    effective_from   DATE NOT NULL,
    effective_to     DATE NULL,
    is_active        TINYINT(1) NOT NULL DEFAULT 0,
    active_flag      TINYINT(1) GENERATED ALWAYS AS (IF(is_active = 1, 1, NULL)) STORED,
    created_by       INT UNSIGNED NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    -- Only one fare matrix may be active at any time (NULLs are ignored by UNIQUE).
    UNIQUE KEY uq_fare_single_active (active_flag),
    CONSTRAINT fk_fare_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_fare_base    CHECK (base_fare >= 0),
    CONSTRAINT chk_fare_basekm  CHECK (base_distance_km >= 0),
    CONSTRAINT chk_fare_rate    CHECK (per_km_rate >= 0),
    CONSTRAINT chk_fare_min     CHECK (minimum_fare >= 0),
    CONSTRAINT chk_fare_dates   CHECK (effective_to IS NULL OR effective_to >= effective_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE bookings (
    id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    booking_code       VARCHAR(24)  NOT NULL DEFAULT '',
    passenger_id       INT UNSIGNED NOT NULL,
    pickup_label       VARCHAR(150) NOT NULL,
    pickup_latitude    DECIMAL(10,7) NOT NULL,
    pickup_longitude   DECIMAL(10,7) NOT NULL,
    dest_label         VARCHAR(150) NOT NULL,
    dest_latitude      DECIMAL(10,7) NOT NULL,
    dest_longitude     DECIMAL(10,7) NOT NULL,
    distance_km        DECIMAL(6,2) NOT NULL,
    est_duration_min   SMALLINT UNSIGNED NOT NULL DEFAULT 15,
    fare_matrix_id     INT UNSIGNED NULL,
    estimated_fare     DECIMAL(8,2) NOT NULL DEFAULT 0.00,
    final_fare         DECIMAL(8,2) NULL,
    status             ENUM('pending','assigned','en_route','in_progress','completed','cancelled','rejected') NOT NULL DEFAULT 'pending',
    driver_id          INT UNSIGNED NULL,
    unit_id            INT UNSIGNED NULL,
    assigned_by        INT UNSIGNED NULL,
    requested_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_at        DATETIME NULL,
    started_at         DATETIME NULL,
    completed_at       DATETIME NULL,
    cancelled_at       DATETIME NULL,
    cancel_reason      VARCHAR(255) NULL,
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- A driver / unit can be inside at most ONE live passenger trip at a time.
    active_driver_key  INT UNSIGNED GENERATED ALWAYS AS (IF(status IN ('assigned','en_route','in_progress'), driver_id, NULL)) STORED,
    active_unit_key    INT UNSIGNED GENERATED ALWAYS AS (IF(status IN ('assigned','en_route','in_progress'), unit_id, NULL)) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_bookings_code (booking_code),
    UNIQUE KEY uq_bookings_active_driver (active_driver_key),
    UNIQUE KEY uq_bookings_active_unit (active_unit_key),
    KEY idx_bookings_status (status, requested_at),
    KEY idx_bookings_passenger (passenger_id, requested_at),
    KEY idx_bookings_driver (driver_id, status),
    CONSTRAINT fk_bookings_passenger FOREIGN KEY (passenger_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_matrix    FOREIGN KEY (fare_matrix_id) REFERENCES fare_matrices (id),
    CONSTRAINT fk_bookings_driver    FOREIGN KEY (driver_id) REFERENCES drivers (id),
    CONSTRAINT fk_bookings_unit      FOREIGN KEY (unit_id) REFERENCES tricycle_units (id),
    CONSTRAINT fk_bookings_assigner  FOREIGN KEY (assigned_by) REFERENCES users (id),
    CONSTRAINT chk_bookings_distance CHECK (distance_km > 0),
    CONSTRAINT chk_bookings_pick_lat CHECK (pickup_latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_bookings_pick_lng CHECK (pickup_longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_bookings_dest_lat CHECK (dest_latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_bookings_dest_lng CHECK (dest_longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_bookings_assigned CHECK (status IN ('pending','cancelled','rejected') OR (driver_id IS NOT NULL AND unit_id IS NOT NULL)),
    CONSTRAINT chk_bookings_completed CHECK (status <> 'completed' OR completed_at IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE booking_status_history (
    id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    booking_id     BIGINT UNSIGNED NOT NULL,
    old_status     VARCHAR(20) NULL,
    new_status     VARCHAR(20) NOT NULL,
    old_driver_id  INT UNSIGNED NULL,
    new_driver_id  INT UNSIGNED NULL,
    changed_by     INT UNSIGNED NULL,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_bsh_booking (booking_id, created_at),
    CONSTRAINT fk_bsh_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_bsh_user    FOREIGN KEY (changed_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- GPS pings from drivers (latest ping is mirrored onto drivers.last_* by a trigger).
CREATE TABLE driver_locations (
    id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    driver_id    INT UNSIGNED NOT NULL,
    booking_id   BIGINT UNSIGNED NULL,
    latitude     DECIMAL(10,7) NOT NULL,
    longitude    DECIMAL(10,7) NOT NULL,
    speed_kmh    DECIMAL(5,1) NULL,
    heading_deg  SMALLINT UNSIGNED NULL,
    recorded_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_dloc_driver_time (driver_id, recorded_at),
    KEY idx_dloc_booking (booking_id, recorded_at),
    CONSTRAINT fk_dloc_driver  FOREIGN KEY (driver_id)  REFERENCES drivers  (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_dloc_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_dloc_lat CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_dloc_lng CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_dloc_heading CHECK (heading_deg IS NULL OR heading_deg <= 360)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
